const {chromium} = require(process.env.WTF_PLAYWRIGHT_MODULE || 'playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const artifacts = process.env.WTF_COOKIES_ARTIFACTS || path.join(process.cwd(), 'output', 'cookies');
fs.mkdirSync(artifacts, {recursive:true});
(async () => {
  const browser = await chromium.launch({channel:'chrome', headless:true});
  const context = await browser.newContext({viewport:{width:1280,height:900}});
  const external = [];
  await context.route('**/*', async route => {
    const url = route.request().url();
    if (url.startsWith('http://localhost:8081/') || url.startsWith('data:') || url.startsWith('blob:')) return route.continue();
    external.push(url);
    // No requests reach third parties during the local audit.
    if (/geowidget.*\.js/i.test(url)) return route.fulfill({contentType:'application/javascript', body:'customElements.define("inpost-geowidget", class extends HTMLElement {});'});
    return route.abort();
  });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:8081/elekt/', {waitUntil:'networkidle'});
  await page.locator('#wtfc-banner').waitFor({state:'visible'});
  assert.equal(await page.locator('iframe[src*="youtube"]').count(),0);
  assert.ok(await page.locator('[data-wtfc-media]').count() >= 5);
  assert.equal(external.filter(url=>/youtube|ytimg|google-analytics|googletagmanager/.test(url)).length,0);
  assert.equal((await context.cookies()).some(cookie=>cookie.name==='pll_language'), false);
  await page.locator('#wtfc-banner [data-wtfc-reject]').click();
  assert.equal(await page.locator('#wtfc-banner').isVisible(),false);
  assert.equal(await page.evaluate(()=>window.wtfCookies.hasConsent('media')),false);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('#wtfc-banner').isVisible(),false);
  assert.equal(await page.locator('iframe[src*="youtube"]').count(),0);
  await page.locator('.wtfc-footer-link').click();
  assert.equal(await page.locator('[data-wtfc-category="media"]').isChecked(),false);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#wtfc-settings').isVisible(),false);
  assert.equal(await page.locator('.wtfc-footer-link').evaluate(el=>el===document.activeElement),true);
  await page.evaluate(()=>{
    window.serviceCounts={start:0,stop:0};
    window.wtfCookies.registerService('test', {category:'media',start(){window.serviceCounts.start++;},stop(){window.serviceCounts.stop++;}});
  });
  await page.locator('[data-wtfc-media-allow]').first().click();
  assert.ok(await page.locator('iframe[src*="youtube"]').count() >= 5);
  assert.equal(await page.evaluate(()=>window.serviceCounts.start),1);
  const cookie = (await context.cookies()).find(cookie=>cookie.name==='wtf_cookies_consent');
  assert.equal(cookie.sameSite,'Lax');
  assert.ok(cookie.expires*1000-Date.now()>179*86400000);
  await page.locator('.wtfc-footer-link').click();
  await page.locator('#wtfc-settings [data-wtfc-reject]').click();
  assert.equal(await page.locator('iframe[src*="youtube"]').count(),0);
  assert.equal(await page.evaluate(()=>window.serviceCounts.stop),1);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('iframe[src*="youtube"]').count(),0);
  await context.addCookies([{name:'wtf_cookies_consent',value:'broken-json',url:'http://localhost:8081/'}]);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('#wtfc-banner').isVisible(),true);
  await page.locator('#wtfc-banner [data-wtfc-accept]').click();
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('#wtfc-banner').isVisible(),false);
  assert.ok(await page.locator('iframe[src*="youtube"]').count()>=5);
  await context.addCookies([{name:'wtf_cookies_consent',value:encodeURIComponent(JSON.stringify({revision:0,at:Date.now(),categories:{media:true}})),url:'http://localhost:8081/'}]);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.locator('#wtfc-banner').isVisible(),true);
  assert.equal(await page.locator('iframe[src*="youtube"]').count(),0);
  await page.setViewportSize({width:360,height:800});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(artifacts,'mobile.png')});
  await page.locator('#wtfc-banner [data-wtfc-open]').click();
  assert.ok(await page.locator('#wtfc-settings').evaluate(el=>el.getBoundingClientRect().width<=innerWidth));
  await page.screenshot({path:path.join(artifacts,'settings-mobile.png')});
  await page.keyboard.press('Escape');
  await page.locator('#wtfc-banner [data-wtfc-reject]').click();
  const beforeMedia = external.filter(url=>/youtube|ytimg/.test(url)).length;
  await page.goto('http://localhost:8081/tsukuyumi/',{waitUntil:'networkidle'});
  assert.equal(await page.locator('iframe[src*="youtube"]').count(),0);
  assert.equal(external.filter(url=>/youtube|ytimg/.test(url)).length,beforeMedia);
  await context.request.get('http://localhost:8081/?add-to-cart=802');
  await page.goto('http://localhost:8081/zamowienie/',{waitUntil:'networkidle'});
  const inpostBefore=external.filter(url=>/geowidget/.test(url)).length;
  assert.equal(inpostBefore,0);
  assert.ok(await page.locator('[data-wtfc-inpost-src]').count()>0);
  // Force only visibility for testing the requested map entrypoint, without ordering.
  const mapButton = page.locator('#wtf-open-locker-map');
  if (await mapButton.count()) {
    await mapButton.evaluate(el=>{ for(let parent=el;parent;parent=parent.parentElement){parent.hidden=false;if(getComputedStyle(parent).display==='none')parent.style.display='block';} });
    await mapButton.click();
    await page.waitForFunction(()=>customElements.get('inpost-geowidget'));
    assert.ok(external.some(url=>/geowidget/.test(url)));
  }
  const nojs = await browser.newContext({javaScriptEnabled:false});
  const nojsPage=await nojs.newPage();
  await nojs.route('**/*',route=>route.request().url().startsWith('http://localhost:8081/')?route.continue():route.abort());
  await nojsPage.goto('http://localhost:8081/elekt/',{waitUntil:'networkidle'});
  assert.equal(await nojsPage.locator('iframe[src*="youtube"]').count(),0);
  assert.equal(await nojsPage.locator('.wtfc-nojs').isVisible(),true);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(artifacts,'result.json'),JSON.stringify({passed:true,checks:['fresh visit','refusal','persistence','YouTube opt-in','withdrawal','integration start/stop','invalid cookie','revision change','mobile layout','keyboard dismissal and focus','Tsukuyumi','InPost lazy SDK','no JavaScript'],pageErrors:errors},null,2));
  console.log('PASS: consent, persistence, media blocking/revocation, mobile, InPost, no-JS.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
